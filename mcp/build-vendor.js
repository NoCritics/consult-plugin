// Bundles the MCP SDK (the server's only npm dependency) into vendor/mcp-sdk.js,
// so a plugin installed from GitHub starts without `npm install`.
// Writes vendor/THIRD_PARTY_LICENSES.md for the packages inside the bundle.
// Run after changing the SDK version: npm run build:vendor
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const mcpFolder = path.dirname(fileURLToPath(import.meta.url));
const vendorFolder = path.join(mcpFolder, 'vendor');
const sdkVersion = JSON.parse(fs.readFileSync(path.join(mcpFolder, 'node_modules', '@modelcontextprotocol', 'sdk', 'package.json'), 'utf8')).version;

// Only what consult.js imports, so the rest of the SDK is left out.
const entry = [
  "export { Server } from '@modelcontextprotocol/sdk/server/index.js';",
  "export { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';",
  "export { CallToolRequestSchema, ListToolsRequestSchema } from '@modelcontextprotocol/sdk/types.js';"
].join('\n');

// Bundled CommonJS packages call require(); in an ES module that needs a real one.
const banner = [
  `// Generated by build-vendor.js from @modelcontextprotocol/sdk ${sdkVersion}. Do not edit.`,
  "import { createRequire as consultCreateRequire } from 'node:module';",
  'const require = consultCreateRequire(import.meta.url);'
].join('\n');

fs.mkdirSync(vendorFolder, { recursive: true });
const result = await build({
  stdin: { contents: entry, resolveDir: mcpFolder, loader: 'js' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: path.join(vendorFolder, 'mcp-sdk.js'),
  banner: { js: banner },
  legalComments: 'none',
  metafile: true,
  logLevel: 'warning'
});

// One entry per package that ended up in the bundle, with its licence text.
const packageFolders = new Set();
for (const inputPath of Object.keys(result.metafile.inputs)) {
  const parts = inputPath.split('/');
  const at = parts.lastIndexOf('node_modules');
  if (at === -1) continue;
  const nameLength = parts[at + 1].startsWith('@') ? 2 : 1;
  packageFolders.add(parts.slice(0, at + 1 + nameLength).join('/'));
}

const sections = ['# Third-party licences', '', 'vendor/mcp-sdk.js contains the following packages.', ''];
for (const packageFolder of [...packageFolders].sort()) {
  const absoluteFolder = path.join(mcpFolder, packageFolder);
  const manifest = JSON.parse(fs.readFileSync(path.join(absoluteFolder, 'package.json'), 'utf8'));
  sections.push(`## ${manifest.name} ${manifest.version} (${manifest.license})`, '');
  const licenceFile = fs.readdirSync(absoluteFolder).find((name) => /^licen[cs]e/i.test(name));
  if (licenceFile) {
    sections.push('```', fs.readFileSync(path.join(absoluteFolder, licenceFile), 'utf8').trim(), '```', '');
  } else {
    sections.push(`No licence file in the package; package.json says ${manifest.license}.`, '');
  }
}
fs.writeFileSync(path.join(vendorFolder, 'THIRD_PARTY_LICENSES.md'), sections.join('\n'));

console.log(`vendor/mcp-sdk.js built from @modelcontextprotocol/sdk ${sdkVersion} (${packageFolders.size} packages)`);
